#!/bin/bash
# Downloads the standalone engine that gets bundled inside the app, so it runs on Macs
# without Homebrew/Python/yt-dlp/ffmpeg. Apple Silicon (arm64).
#
#   bash execution/fetch_engine.sh                 -> .tmp/engine/{python,bin/ffmpeg,bin/ffprobe}
#   bash execution/fetch_engine.sh --update-lock   # after bumping YTDLP_VER: re-resolve + re-pin packages
#
# Everything is checked before use:
#   * Python and ffmpeg against their publisher's SHA-256 files.
#   * yt-dlp and its libraries against execution/engine-requirements.txt, which pins every
#     package to an exact version and hash (pip --require-hashes).
#
# yt-dlp is installed as a library into the bundled Python and run as `python3 -m yt_dlp`.
# (The single-file yt-dlp_macos binary unpacks itself on every call: ~4 s per start vs ~0.3 s.)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/.tmp/engine"
DL="$ROOT/.tmp/engine-downloads"   # untrusted downloads, kept apart from scripts
LOCK="$ROOT/execution/engine-requirements.txt"

# Pinned versions (bump deliberately).
PY_TAG="20261026"
PY_FILE="cpython-3.13.18+${PY_TAG}-aarch64-apple-darwin-install_only_stripped.tar.gz"
YTDLP_VER="2026.11.23"
ENGINE_SPEC="yt-dlp[default,curl-cffi]==${YTDLP_VER}"
FF_BUILD="1789931890_9.0.2"

rm -rf "$OUT" "$DL"
mkdir -p "$OUT/bin" "$DL/wheels"
cd "$DL"

verify() {  # verify <file> <expected-sha256>
  local got; got=$(shasum -a 256 "$1" | awk '{print $1}')
  [[ "$got" == "$2" ]] || { echo "CHECKSUM MISMATCH for $1"; echo " expected $2"; echo " got      $got"; exit 1; }
  echo "  ✓ $1"
}

echo "Python (python-build-standalone $PY_TAG)…"
curl -fsSL -o "$PY_FILE" "https://github.com/astral-sh/python-build-standalone/releases/download/$PY_TAG/$PY_FILE"
curl -fsSL -o py.sums "https://github.com/astral-sh/python-build-standalone/releases/download/$PY_TAG/SHA256SUMS"
verify "$PY_FILE" "$(grep " $PY_FILE\$" py.sums | awk '{print $1}')"
tar -xzf "$PY_FILE" -C "$OUT"          # -> $OUT/python
PY="$OUT/python/bin/python3"
PIP=("$PY" -s -m pip --disable-pip-version-check --no-input)

if [[ "${1:-}" == "--update-lock" ]]; then
  echo "Resolving ${ENGINE_SPEC} and writing a new lock file…"
  "${PIP[@]}" download --quiet --only-binary :all: --dest "$DL/wheels" "$ENGINE_SPEC"
  "$PY" -I - "$DL/wheels" > "$LOCK" <<'EOF'
import hashlib, pathlib, sys
print("# yt-dlp and its libraries for the app's bundled Python (macOS arm64, CPython 3.13).")
print("# Generated by: bash execution/fetch_engine.sh --update-lock")
print("# pip checks every downloaded file against these hashes (--require-hashes).")
for f in sorted(pathlib.Path(sys.argv[1]).glob("*.whl"), key=lambda p: p.name.lower()):
    name, version = f.name.split("-")[:2]
    name = name.replace("_", "-").lower()
    if name == "yt-dlp":
        name = "yt-dlp[default,curl-cffi]"
    print(f"{name}=={version} --hash=sha256:{hashlib.sha256(f.read_bytes()).hexdigest()}")
EOF
  echo "  wrote $LOCK ($(grep -c '==' "$LOCK") packages)"
fi

[[ -f "$LOCK" ]] || { echo "Missing $LOCK. Run: bash execution/fetch_engine.sh --update-lock"; exit 1; }
grep -q "^yt-dlp\[default,curl-cffi\]==${YTDLP_VER} " "$LOCK" || {
  echo "$LOCK pins a different yt-dlp than YTDLP_VER=${YTDLP_VER}. Run with --update-lock."; exit 1; }
echo "yt-dlp ${YTDLP_VER} + libraries (hash-checked)…"
"${PIP[@]}" install --quiet --require-hashes --only-binary :all: --no-warn-script-location -r "$LOCK"
echo "  ✓ $("$PY" -s -m yt_dlp --version) installed"

for tool in ffmpeg ffprobe; do
  echo "$tool ($FF_BUILD, martin-riedl.de static build)…"
  curl -fsSL -o "$tool.zip" "https://ffmpeg.martin-riedl.de/download/macos/arm64/$FF_BUILD/$tool.zip"
  curl -fsSL -o "$tool.zip.sha256" "https://ffmpeg.martin-riedl.de/download/macos/arm64/$FF_BUILD/$tool.zip.sha256"
  verify "$tool.zip" "$(awk '{print $1}' "$tool.zip.sha256")"
  unzip -oq "$tool.zip" -d "$tool-x"
  install -m 755 "$tool-x/$tool" "$OUT/bin/$tool"
done

xattr -cr "$OUT"
"$PY" -I -c "import sys, sqlite3, ssl; print('  python', sys.version.split()[0], 'ok')"
"$OUT/bin/ffmpeg" -hide_banner -version | head -1
echo "Engine ready: $OUT ($(du -sh "$OUT" | awk '{print $1}'))"
